const tabs = document.querySelector('#tabs');
const results = document.querySelector('#results');
const search = document.querySelector('#search');
const categories = ['Всё меню', ...Object.keys(data)];
const requestedCategory = new URLSearchParams(location.search).get('category');
let active = categories.includes(requestedCategory) ? requestedCategory : categories[0];
const normalize = value => value.toLowerCase().replaceAll('ё','е');
const sections = Object.entries(data).flatMap(([category, groups]) =>
  Object.entries(groups).map(([group, entries]) => ({
    category, group, rows: entries.split(';').map(entry => entry.split('|'))
  }))
);

const buttons = categories.map(category => {
  const button = document.createElement('button');
  button.type = 'button';
  button.textContent = category;
  button.addEventListener('click', () => {
    active = category;
    render();
  });
  tabs.append(button);
  return button;
});

function details(name, portion, price, tag) {
  return `<div><${tag}>${name}</${tag}>${portion ? `<span class="portion">${portion}</span>` : ''}</div><span class="price">${price} ₽</span>`;
}

function render() {
  buttons.forEach((button, index) => button.setAttribute('aria-pressed', categories[index] === active));
  const query = normalize(search.value.trim());
  const visible = sections
    .filter(({category}) => active === categories[0] || category === active)
    .map(section => ({
      ...section,
      rows: section.rows.filter(([name]) => normalize(`${section.group} ${name}`).includes(query))
    }))
    .filter(({rows}) => rows.length);
  results.innerHTML = visible.length
    ? `<div class="groups">${visible.map(({group,rows}) => `<section class="group"><h3>${group}</h3>${rows.map(([name,price,portion]) => `<div class="row">${details(name,portion,price,'span')}</div>`).join('')}</section>`).join('')}</div>`
    : '<p class="empty">По вашему запросу ничего не найдено.</p>';
}
search.addEventListener('input', render);
render();
